import { readFile, writeFile } from "node:fs/promises";
const css = await readFile("packages/ui/tokens/src/tokens.css", "utf8");
function declarations(selector) {
  const start = css.indexOf(selector + " {");
  if (start < 0) throw Error(`Missing token selector ${selector}`);
  const body = css.slice(start, css.indexOf("}", start));
  return Object.fromEntries(
    [...body.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [
      name,
      value,
    ]),
  );
}
const values = {
  light: declarations(":root"),
  dark: declarations(':root[data-theme="dark"]'),
  accents: {
    blue: {
      light: declarations(':root[data-accent="blue"]'),
      dark: declarations(':root[data-theme="dark"][data-accent="blue"]'),
    },
    plum: {
      light: declarations(':root[data-accent="plum"]'),
      dark: declarations(':root[data-theme="dark"][data-accent="plum"]'),
    },
  },
};
await writeFile(
  "packages/ui/tokens/src/values.ts",
  "// Generated by pnpm generate:tokens. Portable values contain no DOM or UI dependency.\nexport const designTokens = " +
    JSON.stringify(values, null, 2) +
    " as const;\n",
);
